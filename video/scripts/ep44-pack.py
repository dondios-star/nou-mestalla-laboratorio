"""Losslessly pack original 3D layers as a background plus animated rectangles.

Every reconstructed pixel equals its full-resolution source render. This avoids
storing the identical background in every frame; no temporal interpolation.
"""
import json
from pathlib import Path
from PIL import Image, ImageChops

root=Path('public/assets/ep44/baked')
root.mkdir(parents=True,exist_ok=True)
layout={}
for layer,base_layer,base_index in [('hero','hero',72),('map-a','map-base',0)]:
    frames=sorted(Path(f'out/ep44/bake/{layer}').glob('*.png'))
    bases=sorted(Path(f'out/ep44/bake/{base_layer}').glob('*.png'))
    base=Image.open(bases[base_index]).convert('RGB')
    base.save(root/('hero-base.webp' if layer=='hero' else 'map-base.webp'),lossless=True,method=6)
    bounds=[]
    for file in frames:
        diff=ImageChops.difference(base,Image.open(file).convert('RGB')).getbbox()
        if diff: bounds.append(diff)
    box=(min(b[0] for b in bounds),min(b[1] for b in bounds),max(b[2] for b in bounds),max(b[3] for b in bounds))
    folder=root/layer;folder.mkdir(exist_ok=True)
    for i,file in enumerate(frames):
        src=base if layer=='map-a' and i==0 else Image.open(file).convert('RGB')
        crop=src.crop(box)
        crop.save(folder/f'{i:03d}.webp',lossless=True,method=5)
        restored=base.copy();restored.paste(crop,(box[0],box[1]))
        assert ImageChops.difference(restored,src).getbbox() is None,(layer,i)
    layout[layer]={'x':box[0],'y':box[1],'width':box[2]-box[0],'height':box[3]-box[1],'frames':len(frames)}
    print(layer,layout[layer])
Path('src/episodes/ep44/bake-layout.ts').write_text('// Generated by scripts/ep44-pack.py; native-pixel rectangles.\nexport const bakeLayout = '+json.dumps(layout,indent=2)+' as const;\n')
manifest={'width':1080,'heroHeight':1920,'mapHeight':810,'heroFrames':73,'mapAFrames':127,'fps':60,
          'encoding':'WebP lossless + exact native-pixel delta rectangles','layout':layout,
          'pixelReconstruction':'All rendered source frames compared pixel by pixel during packing',
          'source':'src/episodes/ep44/models.ts + World.tsx','note':'Original procedural 3D. No 30fps conversion. Deliberate static holds.'}
(root/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
